def test_richter_2007_prediction_changes_when_ramps_are_removed(
    monkeypatch: pytest.MonkeyPatch,
    richter_2007_context,
) -> None:
    import simulator.battery.residue as residue

    target = _reference(richter_2007_context, RICHTER_2007, "cai-r3-10", "MgO")
    captured: dict[str, object] = {}
    original_predict = residue._predict_langmuir_residue_cohort
    original_segments = residue._mass_loss_thermal_segments

    def capture_predictions(*args, **kwargs):
        predictions = original_predict(*args, **kwargs)
        captured["predictions"] = predictions
        return predictions

    def final_hold_only(experiment, temperature_K, *, ramp_step_s=60.0):
        maximum, preheat, segments = original_segments(
            experiment, temperature_K, ramp_step_s=ramp_step_s
        )
        return maximum, preheat, (segments[-1],)

    monkeypatch.setattr(
        residue, "_predict_langmuir_residue_cohort", capture_predictions
    )
    monkeypatch.setattr(
        residue, "_mass_loss_thermal_segments", final_hold_only
    )
    residual = _score_one(monkeypatch, richter_2007_context, target)

    assert residual.status is not ResidualStatus.REFUSED, residual.refusal
    predictions = captured["predictions"]
    primary = next(
        row
        for row in predictions
        if row.experiment_id.rsplit("::", 1)[-1] == "cai-r3-10"
        and row.alpha_arm == "alpha_common_unity_sensitivity"
    )
    mutated_oxides = primary.primary_oxide_wt_pct
    assert mutated_oxides == pytest.approx(R3_10_FINAL_HOLD_ONLY_OXIDE_WT_PCT)


