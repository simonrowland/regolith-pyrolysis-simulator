def test_richter_2007_thermal_schedule_segments_include_both_ramps_and_holds(
    richter_2007_context,
) -> None:
    import simulator.battery.residue as residue

    target = _reference(richter_2007_context, RICHTER_2007, "cai-r3-10", "MgO")
    experiment = richter_2007_context.experiments[target.experiment_id]
    _preheat_max_K, _preheat_duration_s, segments = (
        residue._mass_loss_thermal_segments(to_plain(experiment), 2173.15)
    )
    # Richter 2007, physical page 5 / folio 5548: two 500 K ramps at
    # 20 C/min, a 1200 s hold at 1673.15 K; page 6 / folio 5549: R3-10
    # holds 900 s at 2173.15 K. At 60 s per ramp interval, each ramp has 25.
    assert len(segments) == 52
    assert segments[0] == pytest.approx((1183.15, 60.0))
    assert segments[24] == pytest.approx((1663.15, 60.0))
    assert segments[25] == pytest.approx((1673.15, 1200.0))
    assert segments[26] == pytest.approx((1683.15, 60.0))
    assert segments[50] == pytest.approx((2163.15, 60.0))
    assert segments[51] == pytest.approx((2173.15, 900.0))
    assert sum(duration for _temperature, duration in segments) == pytest.approx(5100.0)


def test_one_hold_schedule_matches_the_previous_single_hold_number_exactly() -> None:
    import simulator.battery.residue as residue

    inventory = {"MgO": 0.01}
    channels = (
        residue.ResidueChannel("Mg", "Mg", "MgO", 1.0, "pinned test alpha"),
        residue.ResidueChannel("O2", "O2", None, 1.0, "oxygen gas"),
    )
    pressure_model = lambda _inventory, logp: {
        "Mg": 0.001 / (10.0**logp) ** 0.5,
        "O2": 100_000.0 * 10.0**logp,
    }
    initial_mass_kg = residue._inventory_mass_kg(inventory)
    original = residue._hashimoto_integrate_geometry(
        inventory,
        channels,
        pressure_model,
        temperature_K=1900.0,
        duration_s=600.0,
        steps=20,
        geometry_policy_id="sphere_shrinking",
        initial_area_m2=1.0e-4,
        initial_sample_mass_kg=initial_mass_kg,
    )
    schedule = residue._hashimoto_integrate_langmuir_schedule(
        inventory,
        lambda _temperature: channels,
        lambda _temperature: pressure_model,
        schedule_segments=((1900.0, 600.0),),
        temperature_step_s=30.0,
        single_hold_steps=20,
        geometry_policy_id="sphere_shrinking",
        initial_area_m2=1.0e-4,
        initial_sample_mass_kg=initial_mass_kg,
    )

    assert schedule == original


