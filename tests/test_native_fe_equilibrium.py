    import json

    sim = _reducing_sim()
    inventory = sim.atom_ledger.mol_by_account('process.cleaned_melt')
    controls = dict(
        comp_wt=sim._melt_oxide_wt_pct(), feo_mol=inventory['FeO'],
        fe2o3_mol=inventory['Fe2O3'], T_K=sim.melt.temperature_C+273.15,
        pressure_bar=.01)
    reference = fe_redox.native_fe_equilibrium_extent(
        **controls, gas_fO2_log=lambda n: -14.)
    result = fe_redox.native_fe_equilibrium_extent(
        **controls, gas_fO2_log=lambda n: gas_log)
    notice, = result['model_limit_notices']
    assert notice['status'] == 'model_limit'
    assert notice['root'] == 'gas'
    assert abs(notice['residual_dex']) > fe_redox.NATIVE_FE_ROOT_TOLERANCE_DEX
    low, high = notice['last_bracket_mol']
    assert 0. < low <= result['gas_root_mol'] <= high <= inventory['FeO']
    assert high-low < 1e-8
    low_gap, high_gap = notice['last_bracket_residual_dex']
    assert low_gap < 0. < high_gap
    # The unresolved gas root is beyond the well-resolved melt root. The
    # actual extent retains the same limiting melt equilibrium as at 1e-14.
    assert result['native_fe_mol'] == reference['native_fe_mol']
    assert result['native_fe_mol'] == result['melt_root_mol'] < low
    assert result['limit'] == 'melt'
    assert abs(result['fO2_after_log'] - result['iw_bound_after_log']) <= (
        fe_redox.NATIVE_FE_ROOT_TOLERANCE_DEX)
    assert 'model_limit_notices' not in reference
    json.dumps(notice, allow_nan=False)


